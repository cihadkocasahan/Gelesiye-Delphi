import urllib.request
import json

url = 'https://raw.githubusercontent.com/nejdetkadir/il-ilce-semt-mahalleler/master/data/data.json'
with urllib.request.urlopen(url) as r:
    data = json.loads(r.read().decode('utf-8'))

lines = []
lines.append('unit uDbIlIlceSeed;')
lines.append('')
lines.append('interface')
lines.append('')
lines.append('uses')
lines.append('  FireDAC.Comp.Client,')
lines.append('  FireDAC.Stan.Param,')
lines.append('  System.SysUtils,')
lines.append('  System.Classes;')
lines.append('')
lines.append('procedure SeedIlIlce(AConn: TFDConnection);')
lines.append('')
lines.append('implementation')
lines.append('')
lines.append('const')
lines.append('  C_IL_DATA: array[0..80] of string = (')

for i, c in enumerate(data):
    towns = ','.join(t['name'] for t in c['towns'])
    s = f"    '{c['name']}:{towns}'"
    if i < len(data) - 1:
        s += ','
    lines.append(s)

lines.append('  );')
lines.append('')
lines.append('procedure SeedIlIlce(AConn: TFDConnection);')
lines.append('var')
lines.append('  I, ColonPos: Integer;')
lines.append('  IlAdi, IlcelerStr, IlceAdi: string;')
lines.append('  TownList: TArray<string>;')
lines.append('  QryIl, QryIlce: TFDQuery;')
lines.append('begin')
lines.append('  if AConn = nil then Exit;')
lines.append('  AConn.StartTransaction;')
lines.append('  QryIl := TFDQuery.Create(nil);')
lines.append('  QryIlce := TFDQuery.Create(nil);')
lines.append('  try')
lines.append('    QryIl.Connection := AConn;')
lines.append('    QryIl.SQL.Text := \'INSERT INTO ILLER (ID, AD) VALUES (:ID, :AD)\';')
lines.append('    QryIlce.Connection := AConn;')
lines.append('    QryIlce.SQL.Text := \'INSERT INTO ILCELER (IL_ID, AD) VALUES (:IL_ID, :AD)\';')
lines.append('')
lines.append('    for I := 0 to High(C_IL_DATA) do')
lines.append('    begin')
lines.append('      ColonPos := Pos(\':\', C_IL_DATA[I]);')
lines.append('      if ColonPos > 0 then')
lines.append('      begin')
lines.append('        IlAdi := Copy(C_IL_DATA[I], 1, ColonPos - 1);')
lines.append('        IlcelerStr := Copy(C_IL_DATA[I], ColonPos + 1, MaxInt);')
lines.append('        QryIl.ParamByName(\'ID\').AsInteger := I + 1;')
lines.append('        QryIl.ParamByName(\'AD\').AsString := IlAdi;')
lines.append('        QryIl.ExecSQL;')
lines.append('')
lines.append('        TownList := IlcelerStr.Split([\',\']);')
lines.append('        for IlceAdi in TownList do')
lines.append('        begin')
lines.append('          if Trim(IlceAdi) <> \'\' then')
lines.append('          begin')
lines.append('            QryIlce.ParamByName(\'IL_ID\').AsInteger := I + 1;')
lines.append('            QryIlce.ParamByName(\'AD\').AsString := Trim(IlceAdi);')
lines.append('            QryIlce.ExecSQL;')
lines.append('          end;')
lines.append('        end;')
lines.append('      end;')
lines.append('    end;')
lines.append('    AConn.Commit;')
lines.append('  except')
lines.append('    AConn.Rollback;')
lines.append('    QryIl.Free;')
lines.append('    QryIlce.Free;')
lines.append('    raise;')
lines.append('  end;')
lines.append('  QryIl.Free;')
lines.append('  QryIlce.Free;')
lines.append('end;')
lines.append('')
lines.append('end.')
lines.append('')

out_path = r'src\Data\uDbIlIlceSeed.pas'
content = '\r\n'.join(lines)
with open(out_path, 'w', encoding='utf-8-sig', newline='\r\n') as f:
    f.write(content)

print(f'Generated successfully: {out_path} ({len(lines)} lines, {len(content)} bytes)')
